    private void BtnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAgregarActionPerformed
      String alumno = TxtAlumno.getText();

    if (alumno.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "El nombre no puede estar vacío",
                "Precaución",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try {
        double calificacion = Double.parseDouble(TxtCalificacion.getText());

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) TblAlumnoCalificacion.getModel();

        int fila = TblAlumnoCalificacion.getSelectedRow();

        if (fila == -1) {
            // Agregar nuevo alumno
            modelo.addRow(new Object[]{alumno, calificacion});
        } else {
            // Modificar alumno seleccionado
            modelo.setValueAt(alumno, fila, 0);
            modelo.setValueAt(calificacion, fila, 1);
        }

        TxtAlumno.setText("");
        TxtCalificacion.setText("");
        TblAlumnoCalificacion.clearSelection();
        TxtAlumno.requestFocus();

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "La calificación debe ser un número",
                "Precaución",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
    
    }

        // TODO add your handling code here:
    }//GEN-LAST:event_BtnAgregarActionPerformed

    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
         javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) TblAlumnoCalificacion.getModel();

    int fila = TblAlumnoCalificacion.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecciona una fila para eliminar",
                "Precaución",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int opcion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Realmente desea eliminar el registro?",
            "Eliminar registro",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (opcion == javax.swing.JOptionPane.YES_OPTION) {
        modelo.removeRow(fila);
    }// TODO add your handling code here:
        
        
        
        
    }//GEN-LAST:event_BtnEliminarActionPerformed

